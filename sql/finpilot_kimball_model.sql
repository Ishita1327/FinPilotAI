-- SECTION 1: Set up the Snowflake warehouse, database, and analytics schema.

USE WAREHOUSE SNOWFLAKE_LEARNING_WH;
USE DATABASE FINPILOT_DB;

CREATE SCHEMA IF NOT EXISTS ANALYTICS;
USE SCHEMA ANALYTICS;

SHOW SCHEMAS IN DATABASE FINPILOT_DB;


-- SECTION 2: Create the date dimension and validate unique date keys.

CREATE OR REPLACE TABLE FINPILOT_DB.ANALYTICS.DIM_DATE AS
SELECT DISTINCT
    TO_NUMBER(TO_CHAR(TRANSACTION_DATE, 'YYYYMMDD')) AS DATE_KEY,
    TO_DATE(TRANSACTION_DATE) AS FULL_DATE,
    YEAR(TRANSACTION_DATE) AS YEAR,
    QUARTER(TRANSACTION_DATE) AS QUARTER,
    MONTH(TRANSACTION_DATE) AS MONTH,
    MONTHNAME(TRANSACTION_DATE) AS MONTH_NAME
FROM FINPILOT_DB.RAW.PERSONAL_TRANSACTIONS
WHERE TRANSACTION_DATE IS NOT NULL;

SELECT *
FROM FINPILOT_DB.ANALYTICS.DIM_DATE
ORDER BY FULL_DATE
LIMIT 10;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT DATE_KEY) AS UNIQUE_DATE_KEYS
FROM FINPILOT_DB.ANALYTICS.DIM_DATE;


-- SECTION 3: Create the category dimension and validate unique category keys.

CREATE OR REPLACE TABLE FINPILOT_DB.ANALYTICS.DIM_CATEGORY AS
SELECT
    ROW_NUMBER() OVER (
        ORDER BY CATEGORY_NAME NULLS FIRST
    ) AS CATEGORY_KEY,
    CATEGORY_NAME
FROM (
    SELECT DISTINCT
        CATEGORY AS CATEGORY_NAME
    FROM FINPILOT_DB.RAW.PERSONAL_TRANSACTIONS
);

SELECT *
FROM FINPILOT_DB.ANALYTICS.DIM_CATEGORY
ORDER BY CATEGORY_KEY;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CATEGORY_KEY) AS UNIQUE_CATEGORY_KEYS
FROM FINPILOT_DB.ANALYTICS.DIM_CATEGORY;


-- SECTION 4: Create the account dimension and validate unique account keys.

CREATE OR REPLACE TABLE FINPILOT_DB.ANALYTICS.DIM_ACCOUNT AS
SELECT
    ROW_NUMBER() OVER (
        ORDER BY ACCOUNT_NAME NULLS FIRST
    ) AS ACCOUNT_KEY,
    ACCOUNT_NAME
FROM (
    SELECT DISTINCT
        ACCOUNT_NAME
    FROM FINPILOT_DB.RAW.PERSONAL_TRANSACTIONS
);

SELECT *
FROM FINPILOT_DB.ANALYTICS.DIM_ACCOUNT
ORDER BY ACCOUNT_KEY;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT ACCOUNT_KEY) AS UNIQUE_ACCOUNT_KEYS
FROM FINPILOT_DB.ANALYTICS.DIM_ACCOUNT;


-- SECTION 5: Create the merchant dimension and validate unique merchant keys.

CREATE OR REPLACE TABLE FINPILOT_DB.ANALYTICS.DIM_MERCHANT AS
SELECT
    ROW_NUMBER() OVER (
        ORDER BY MERCHANT_DESCRIPTION NULLS FIRST
    ) AS MERCHANT_KEY,
    MERCHANT_DESCRIPTION
FROM (
    SELECT DISTINCT
        DESCRIPTION AS MERCHANT_DESCRIPTION
    FROM FINPILOT_DB.RAW.PERSONAL_TRANSACTIONS
);

SELECT *
FROM FINPILOT_DB.ANALYTICS.DIM_MERCHANT
ORDER BY MERCHANT_KEY
LIMIT 20;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT MERCHANT_KEY) AS UNIQUE_MERCHANT_KEYS
FROM FINPILOT_DB.ANALYTICS.DIM_MERCHANT;


-- SECTION 6: Create the fact table by linking transactions to all four dimensions.

CREATE OR REPLACE TABLE FINPILOT_DB.ANALYTICS.FACT_TRANSACTIONS AS
SELECT
    ROW_NUMBER() OVER (
        ORDER BY
            T.TRANSACTION_DATE,
            T.DESCRIPTION,
            T.AMOUNT,
            T.ACCOUNT_NAME,
            T.CATEGORY,
            T.SIGNED_AMOUNT
    ) AS TRANSACTION_KEY,

    D.DATE_KEY,
    C.CATEGORY_KEY,
    A.ACCOUNT_KEY,
    M.MERCHANT_KEY,

    T.AMOUNT,
    T.SIGNED_AMOUNT,
    T.TRANSACTION_TYPE,
    T.IS_TRANSFER_CANDIDATE,
    T.IS_SUBSCRIPTION_CANDIDATE,
    T.SOURCE_MONTH,
    T.YEAR_MONTH

FROM FINPILOT_DB.RAW.PERSONAL_TRANSACTIONS T

LEFT JOIN FINPILOT_DB.ANALYTICS.DIM_DATE D
    ON TO_DATE(T.TRANSACTION_DATE) = D.FULL_DATE

LEFT JOIN FINPILOT_DB.ANALYTICS.DIM_CATEGORY C
    ON T.CATEGORY IS NOT DISTINCT FROM C.CATEGORY_NAME

LEFT JOIN FINPILOT_DB.ANALYTICS.DIM_ACCOUNT A
    ON T.ACCOUNT_NAME IS NOT DISTINCT FROM A.ACCOUNT_NAME

LEFT JOIN FINPILOT_DB.ANALYTICS.DIM_MERCHANT M
    ON T.DESCRIPTION IS NOT DISTINCT FROM M.MERCHANT_DESCRIPTION;


-- SECTION 7: Validate transaction counts, financial totals, key uniqueness, and dimension relationships.

SELECT
    (SELECT COUNT(*)
     FROM FINPILOT_DB.RAW.PERSONAL_TRANSACTIONS) AS RAW_COUNT,

    (SELECT COUNT(*)
     FROM FINPILOT_DB.ANALYTICS.FACT_TRANSACTIONS) AS FACT_COUNT;

SELECT
    'RAW' AS SOURCE,
    SUM(AMOUNT) AS TOTAL_AMOUNT,
    SUM(SIGNED_AMOUNT) AS TOTAL_SIGNED_AMOUNT
FROM FINPILOT_DB.RAW.PERSONAL_TRANSACTIONS

UNION ALL

SELECT
    'FACT' AS SOURCE,
    SUM(AMOUNT),
    SUM(SIGNED_AMOUNT)
FROM FINPILOT_DB.ANALYTICS.FACT_TRANSACTIONS;

SELECT
    COUNT(*) AS TOTAL_FACT_ROWS,
    COUNT(DISTINCT TRANSACTION_KEY) AS UNIQUE_TRANSACTION_KEYS,
    COUNT_IF(DATE_KEY IS NULL) AS MISSING_DATE_KEYS,
    COUNT_IF(CATEGORY_KEY IS NULL) AS MISSING_CATEGORY_KEYS,
    COUNT_IF(ACCOUNT_KEY IS NULL) AS MISSING_ACCOUNT_KEYS,
    COUNT_IF(MERCHANT_KEY IS NULL) AS MISSING_MERCHANT_KEYS
FROM FINPILOT_DB.ANALYTICS.FACT_TRANSACTIONS;

SELECT
    COUNT_IF(D.DATE_KEY IS NULL) AS INVALID_DATE_RELATIONSHIPS,
    COUNT_IF(C.CATEGORY_KEY IS NULL) AS INVALID_CATEGORY_RELATIONSHIPS,
    COUNT_IF(A.ACCOUNT_KEY IS NULL) AS INVALID_ACCOUNT_RELATIONSHIPS,
    COUNT_IF(M.MERCHANT_KEY IS NULL) AS INVALID_MERCHANT_RELATIONSHIPS

FROM FINPILOT_DB.ANALYTICS.FACT_TRANSACTIONS F

LEFT JOIN FINPILOT_DB.ANALYTICS.DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY

LEFT JOIN FINPILOT_DB.ANALYTICS.DIM_CATEGORY C
    ON F.CATEGORY_KEY = C.CATEGORY_KEY

LEFT JOIN FINPILOT_DB.ANALYTICS.DIM_ACCOUNT A
    ON F.ACCOUNT_KEY = A.ACCOUNT_KEY

LEFT JOIN FINPILOT_DB.ANALYTICS.DIM_MERCHANT M
    ON F.MERCHANT_KEY = M.MERCHANT_KEY;


-- SECTION 8: Analyze monthly expenses by category, account, and merchant using the star schema.

SELECT
    D.YEAR,
    D.MONTH,
    C.CATEGORY_NAME,
    COUNT(*) AS TRANSACTION_COUNT,
    ROUND(SUM(-F.SIGNED_AMOUNT), 2) AS TOTAL_EXPENSES

FROM FINPILOT_DB.ANALYTICS.FACT_TRANSACTIONS F

JOIN FINPILOT_DB.ANALYTICS.DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY

JOIN FINPILOT_DB.ANALYTICS.DIM_CATEGORY C
    ON F.CATEGORY_KEY = C.CATEGORY_KEY

WHERE F.SIGNED_AMOUNT < 0
  AND COALESCE(F.IS_TRANSFER_CANDIDATE, FALSE) = FALSE

GROUP BY
    D.YEAR,
    D.MONTH,
    C.CATEGORY_NAME

ORDER BY
    D.YEAR,
    D.MONTH,
    TOTAL_EXPENSES DESC;

SELECT
    D.YEAR,
    D.MONTH,
    C.CATEGORY_NAME,
    A.ACCOUNT_NAME,

    COUNT(*) AS TRANSACTION_COUNT,

    ROUND(SUM(-F.SIGNED_AMOUNT), 2) AS TOTAL_EXPENSES,

    COUNT(DISTINCT M.MERCHANT_KEY) AS UNIQUE_MERCHANTS

FROM FINPILOT_DB.ANALYTICS.FACT_TRANSACTIONS F

JOIN FINPILOT_DB.ANALYTICS.DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY

JOIN FINPILOT_DB.ANALYTICS.DIM_CATEGORY C
    ON F.CATEGORY_KEY = C.CATEGORY_KEY

JOIN FINPILOT_DB.ANALYTICS.DIM_ACCOUNT A
    ON F.ACCOUNT_KEY = A.ACCOUNT_KEY

JOIN FINPILOT_DB.ANALYTICS.DIM_MERCHANT M
    ON F.MERCHANT_KEY = M.MERCHANT_KEY

WHERE F.SIGNED_AMOUNT < 0
  AND COALESCE(F.IS_TRANSFER_CANDIDATE, FALSE) = FALSE

GROUP BY
    D.YEAR,
    D.MONTH,
    C.CATEGORY_NAME,
    A.ACCOUNT_NAME

ORDER BY
    D.YEAR,
    D.MONTH,
    TOTAL_EXPENSES DESC;